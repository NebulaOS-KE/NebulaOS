#!/usr/bin/env python3
"""Generate the reference for the firmware overlay's runtime helpers.

These are the executable files the image installs outside `/etc/init.d` - shell
and Python helpers that the boot services, the Moonraker component and each
other call at runtime. There are over fifty and they are the least discoverable
part of the image: a developer meets one by finding its name inside another
script.

So the column that earns this page is **called by**, found by searching the
whole overlay for each helper's name rather than inferred from it. A helper with
no caller in the image is reported as such - that is a fact about the image, not
a gap in the search.

The purpose is each file's own header comment, kept whole. These headers are
unusually good; summarising them would lose the reasoning that makes them worth
reading.

Five of these have ordinary system names and are not what they look like
(`sudo`, `supervisorctl`, `passwd`, `sftp-server`, `git`). They are flagged,
because assuming standard behaviour from the name is the specific mistake this
page exists to prevent.

Usage:  gen_firmware_runtime_helpers.py <firmware-checkout> <out-file>
"""
import datetime, os, re, subprocess, sys, textwrap
import _srccommit

OVERLAY = "scripts/build/overlay"
SKIP_EXT = (".conf", ".cfg", ".json", ".txt", ".png", ".service")
# Names that collide with a standard system command. The image's version is not
# the standard one, and that is the point.
IMPOSTORS = {
    "sudo": "an adapter, not sudo",
    "supervisorctl": "a deliberate stand-in so Moonraker believes a supervisor exists",
    "passwd": "redirects, because the image's /etc/shadow is read-only",
    "sftp-server": "relocates SFTP to /opt/printer_data",
    "git": "a wrapper, first on Moonraker's PATH",
}


def header(path):
    """The file's own header comment block, as its stated purpose."""
    lines = []
    try:
        with open(path, errors="replace") as fh:
            first = fh.readline()
            if not first.startswith("#!"):
                fh.seek(0)
            for line in fh:
                st = line.strip()
                if st.startswith("#"):
                    lines.append(st.lstrip("#").strip())
                elif st.startswith('"""') or st.startswith("'''"):
                    continue
                elif not st:
                    if lines:
                        lines.append("")
                    continue
                else:
                    break
    except OSError:
        return ""
    while lines and not lines[-1]:
        lines.pop()
    return "\n".join(lines).strip()


def helpers(root):
    ov = os.path.join(root, OVERLAY)
    out = []
    for dirpath, _d, filenames in os.walk(ov):
        if "init.d" in dirpath:
            continue
        for f in sorted(filenames):
            full = os.path.join(dirpath, f)
            if f.endswith(SKIP_EXT):
                continue
            if not (f.endswith(".sh") or os.access(full, os.X_OK)):
                continue
            out.append((os.path.relpath(full, ov), full))
    return sorted(out)


def callers(root, name, own_rel):
    """Files in the firmware repository that name this helper."""
    try:
        res = subprocess.run(
            ["git", "-C", root, "grep", "-l", "--", name],
            capture_output=True, text=True)
    except OSError:
        return []
    out = []
    for line in res.stdout.split("\n"):
        line = line.strip()
        if not line or line.endswith(own_rel):
            continue
        out.append(line)
    return out


def shorten(paths, limit=6):
    pretty = []
    for p in paths:
        p = re.sub(r"^scripts/build/overlay/", "", p)
        pretty.append(p)
    if len(pretty) > limit:
        return pretty[:limit] + [f"...and {len(pretty) - limit} more"]
    return pretty


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    sha, _ = _srccommit.source_commit(root)
    items = helpers(root)
    uncalled = 0
    L = [f"<!-- Generated by documentation/agent/tools/gen_firmware_runtime_helpers.py "
         f"from NebulaOS-firmware@{sha[:7]} on {datetime.date.today().isoformat()}. "
         f"Do not edit by hand. -->", "",
         "# Runtime helper reference", "",
         "Every executable the image installs outside `/etc/init.d`: the shell and Python "
         "helpers that boot services, the Moonraker component and each other call at runtime.",
         "",
         f"Source: `NebulaOS-firmware` at `{sha[:7]}`, `{OVERLAY}/`. "
         f"**{len(items)} helpers.**", "",
         "## Five of these are not what their names suggest", "",
         "The image installs executables with ordinary system names that do **not** behave "
         "like the system commands they shadow. Assuming otherwise is the specific mistake "
         "this page exists to prevent.", "",
         "| Name | What it actually is |", "|---|---|"]
    for n, what in sorted(IMPOSTORS.items()):
        L.append(f"| `{n}` | {what} |")
    L += ["",
          "## How to read this", "",
          "**Installed path** is where the file lands on the printer - the overlay mirrors "
          "the root filesystem, so the path below the overlay directory is the path on the "
          "machine.", "",
          "**Called by** is found by searching the whole repository for the helper's name, "
          "not inferred from it. A helper with nothing listed is not referenced anywhere in "
          "this repository: it is invoked by something outside it, or it is dead weight. "
          "Either way that is a fact worth seeing, so it is stated rather than left blank.",
          "",
          "**Purpose** is the file's own header comment, kept whole. These headers carry the "
          "reasoning behind decisions that look arbitrary from outside, and summarising them "
          "would lose exactly that.", "",
          "**Nothing here is hardware-verified.** Every statement is read from source.", ""]

    for rel, full in items:
        name = os.path.basename(rel)
        L.append(f"## `/{rel}`")
        L.append("")
        if name in IMPOSTORS:
            L.append(f"> **Not the system `{name}`** - {IMPOSTORS[name]}.")
            L.append("")
        who = shorten(callers(root, name, rel))
        if who:
            shown = [w for w in who if not w.startswith("...and ")]
            more = [w for w in who if w.startswith("...and ")]
            L.append("Called by: " + ", ".join(f"`{w}`" for w in shown)
                     + (f", {more[0]}." if more else "."))
        else:
            uncalled += 1
            L.append("*Not referenced anywhere else in this repository.*")
        L.append("")
        h = header(full)
        if h:
            for para in h.split("\n\n"):
                lines = [x for x in para.split("\n") if x.strip()]
                if not lines:
                    continue
                # A paragraph that is really a list or a two-column table loses
                # its meaning when reflowed into prose - the first version of
                # this page turned the backlight interface table into a
                # run-on sentence. Keep that shape verbatim.
                if any(re.match(r"^(\s{2,}|[-*]\s|\S+\s{2,}\S)", x) for x in lines):
                    L.append("```")
                    L.extend(lines)
                    L.append("```")
                    L.append("")
                    continue
                flat = " ".join(para.split())
                if flat:
                    L.extend(textwrap.wrap(flat, 95))
                    L.append("")
        else:
            L.append("*No header comment.*")
            L.append("")

    open(out_path, "w").write("\n".join(L) + "\n")
    print(f"{len(items)} helpers, {len(items) - uncalled} with callers found, "
          f"{uncalled} unreferenced -> {out_path}")


if __name__ == "__main__":
    main()
