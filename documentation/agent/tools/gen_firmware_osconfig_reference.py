#!/usr/bin/env python3
"""Generate the reference for the `nebulaos_osconfig` helper modules.

These seventeen-plus modules are where every OS setting is actually read and
written. The Moonraker API reference stops at the endpoint; this one picks up
where it stops: which `nebulaos-osconfig DOMAIN VERB` commands reach a module,
what each public function returns, and the module's own stated purpose.

Nothing is written by hand. The purpose is the module's own header - its
docstring if it has one, otherwise its leading comment block, which is the form
most of these use. The verbs come from the CLI dispatcher and the return keys
from `ast`, both shared with gen_firmware_api_responses.py so the two references
cannot drift apart.

A function whose returns cannot be read is listed with its keys left blank. That
is the same rule as everywhere else here: a blank is honest, a guess is not.

Usage:  gen_firmware_osconfig_reference.py <firmware-checkout> <out-file>
"""
import ast, datetime, os, sys, textwrap
import _srccommit
import gen_firmware_api_responses as _resp

OSCONFIG = _resp.OSCONFIG
SKIP = {"__init__.py"}


def header(path):
    """The module's own stated purpose: its docstring, or its leading comment."""
    src = open(path).read()
    doc = ast.get_docstring(ast.parse(src))
    if doc:
        return " ".join(doc.split())
    lines = []
    for line in src.splitlines():
        if line.startswith("#"):
            lines.append(line.lstrip("#").strip())
        elif lines:
            break
        elif line.strip() and not line.startswith("#"):
            break
    text = " ".join(x for x in lines if x)
    return text


def public_functions(path):
    tree = ast.parse(open(path).read())
    fns = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
    out = {}
    for name, fn in fns.items():
        if name.startswith("_"):
            continue
        args = [a.arg for a in fn.args.args]
        out[name] = {"args": args,
                     "keys": _resp.return_keys(fn, fns),
                     "doc": " ".join((ast.get_docstring(fn) or "").split())}
    return out


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    sha, sha_from = _srccommit.source_commit(root)
    base = os.path.join(root, OSCONFIG)
    disp = _resp.dispatch(os.path.join(base, "cli.py"))
    # module -> {function: [(domain, verb), ...]}
    reached = {}
    for (d, v), targets in disp.items():
        for t in targets:
            mod, fn = t.split(".", 1)
            reached.setdefault(mod, {}).setdefault(fn, []).append((d, v))

    mods = sorted(f for f in os.listdir(base) if f.endswith(".py") and f not in SKIP)
    total_fn = with_keys = 0
    L = [f"<!-- Generated by documentation/agent/tools/gen_firmware_osconfig_reference.py "
         f"from NebulaOS-firmware@{sha[:7]} on {datetime.date.today().isoformat()}. "
         f"Do not edit by hand. -->", "",
         "# `nebulaos-osconfig` helper reference", "",
         "Every OS setting a printer has is read and written here. The "
         "[API reference](MOONRAKER-API.md) stops at the endpoint; this page picks up where "
         "it stops.", "",
         f"Source: `NebulaOS-firmware` at `{sha[:7]}`, `{OSCONFIG}/`. "
         f"**{len(mods)} modules.**", "",
         "## The contract", "",
         "`nebulaos-osconfig` is a command-line program: **argv in, one JSON object out.** It "
         "is run by the Moonraker component as a subprocess, which is the whole reason the "
         "privilege boundary works - the component never writes a system file itself.", "",
         "```",
         "nebulaos-osconfig DOMAIN VERB [--option value]...",
         "```", "",
         "It prints `{\"ok\": true, ...}` merged with the helper's own result, or "
         "`{\"ok\": false, \"error\": \"<CODE>\", \"message\": \"...\"}`, and never a traceback - "
         "the dispatcher catches every exception and turns it into that contract. Read-only "
         "verbs are listed in `cli.py`'s `READ_ONLY` set and are the only ones that skip the "
         "audit log; every change writes one line to the persistent system log.", "",
         "## How to read the tables", "",
         "**Reached by** is the `DOMAIN VERB` that routes to the function, taken from the "
         "dispatcher rather than from the function's name. A function with nothing there is "
         "not reachable from the command line: it is used by another module, by a boot "
         "service, or by a test.", "",
         "**Result keys** are the keys that function's own `return` statements carry, "
         "extracted with `ast`. A blank means the returns could not be read - not that the "
         "function returns nothing.", "",
         "**No module here is hardware-verified.** Everything is read from source.", ""]

    for f in mods:
        path = os.path.join(base, f)
        mod = f[:-3]
        L.append(f"## `{mod}.py`")
        L.append("")
        h = header(path)
        if h:
            # These headers are long - several are a page of the author's own
            # reasoning - and worth keeping whole rather than truncating to a
            # first sentence. Wrapped so the file stays readable.
            L.extend(textwrap.wrap(h, 95))
            L.append("")
        fns = public_functions(path)
        if not fns:
            L.append("*No public functions.*")
            L.append("")
            continue
        L.append("| Function | Reached by | Result keys |")
        L.append("|---|---|---|")
        for name in sorted(fns):
            info = fns[name]
            total_fn += 1
            via = reached.get(mod, {}).get(name, [])
            via_s = ", ".join(f"`{d} {v}`" for d, v in sorted(set(via))) or "-"
            if info["keys"]:
                with_keys += 1
                keys_s = ", ".join(f"`{k}`" for k in sorted(info["keys"]))
            else:
                keys_s = "-"
            L.append(f"| `{name}({', '.join(info['args'])})` | {via_s} | {keys_s} |")
        L.append("")

    open(out_path, "w").write("\n".join(L) + "\n")
    print(f"{len(mods)} modules, {total_fn} public functions, "
          f"{with_keys} with resolved result keys -> {out_path}")


if __name__ == "__main__":
    main()
