#!/usr/bin/env python3
"""Generate the per-module reference for the Klipper extensions.

`COMMANDS.md` answers "what can I run", `CONFIG.md` answers "what can I set".
Neither answers the question a developer actually opens the repository with:
**what is this file, and do I need to care about it?**

So one section per module: its own header as purpose, the commands it registers,
the options it reads, whether a test covers it, and - for the vendored ones -
who wrote it and where it came from. Everything is extracted with `ast` by the
same scanner the other two references use, so the three cannot drift apart.

Provenance is not inferred from the code. It is read from `VENDORED.md`'s own
summary table, because misattributing community work as NebulaOS's own is the
one error in this repository that would be a discourtesy rather than a bug.

Usage:  gen_extensions_modules.py <extensions-checkout> <out-file>
"""
import ast, datetime, os, re, sys, textwrap
import _srccommit
import gen_extensions_reference as _ref


def vendored(root):
    """{module file: (author, upstream)} from VENDORED.md's summary table."""
    path = os.path.join(root, "VENDORED.md")
    out = {}
    if not os.path.exists(path):
        return out
    for line in open(path):
        if not line.startswith("| `extras/"):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 3:
            continue
        files = re.findall(r"`extras/([\w.]+\.py)`", cells[0])
        for f in files:
            out[f] = (cells[1], cells[2])
    return out


def tests_for(name, ext, tests):
    """Test files that cover a module.

    Not `test_<module>.py`. That rule looked obvious and was wrong in both
    directions: `nozzle_clear`, `z_compensate` and `nebulaos_z_offset_probe` are
    covered by files with other names (`test_nozzle_clear_native.py`,
    `test_z_compensate_*.py`, `test_z_offset_probe_*.py`), while an older record
    in this project listed `nebulaos_compat` and `nebulaos_temperature_mcu` as
    untested when they have test files - they are merely excluded from the
    standalone run because they import real Klipper.

    So: a test covers a module if it names it. Checked by reading, not by
    matching filenames.
    """
    out = []
    for t in sorted(tests):
        try:
            src = open(os.path.join(ext, t), errors="replace").read()
        except OSError:
            continue
        if re.search(r"\b%s\b" % re.escape(name), src):
            out.append(t)
    return out


def main():
    root, out_path = sys.argv[1], sys.argv[2]
    sha, _ = _srccommit.source_commit(root)
    ext = os.path.join(root, "extras")
    mods = sorted(f for f in os.listdir(ext)
                  if f.endswith(".py") and not f.startswith("test_"))
    tests = {f for f in os.listdir(ext) if f.startswith("test_")}
    prov = vendored(root)

    L = [f"<!-- Generated by documentation/agent/tools/gen_extensions_modules.py "
         f"from NebulaOS-klipper-extensions@{sha[:7]} on "
         f"{datetime.date.today().isoformat()}. Do not edit by hand. -->", "",
         "# Module reference", "",
         "One section per file in `extras/`. "
         "[Commands](Commands) answers *what can I run*, "
         "[Configuration](Configuration) answers *what can I set*; this answers "
         "*what is this file, and do I need to care about it*.", "",
         f"Source: `NebulaOS-klipper-extensions` at `{sha[:7]}`. "
         f"**{len(mods)} modules.**", "",
         "## What each section shows", "",
         "**Purpose** is the module's own header, kept whole. These authors explain their "
         "reasoning in the header, and summarising it would discard the part worth reading.",
         "",
         "**Registers** are the G-code commands the module registers, from its own "
         "`register_command` calls. A command marked *replaces upstream* is registered after "
         "de-registering Klipper's own - it does **not** behave as stock Klipper, and anyone "
         "arriving from stock needs to know before debugging it.", "",
         "**Reads** counts the configuration options; the options themselves are in "
         "[Configuration](Configuration).", "",
         "**Tested by** lists every test file that names the module - not just a file called "
         "`test_<module>.py`, which misses the ones named after what they test rather "
         "than after the file. A module no test refers to is marked as such.", "",
         "**Author** appears only for vendored modules and is read from "
         "[VENDORED.md](https://github.com/NebulaOS-KE/NebulaOS-klipper-extensions/blob/main/VENDORED.md), not inferred. Community-authored code is never "
         "presented here as NebulaOS's own work.", "",
         "**Nothing here is hardware-verified.** Everything is read from source.", "",
         "## The five modules no test refers to", "",
         "`bl24c16f`, `calibrate_shaper_config`, `gcode_shell_command`, `motor_constants` and "
         "`virtual_pins` - **all five are vendored community modules**, and every module "
         "NebulaOS wrote is referred to by at least one test. That is a coherent position "
         "rather than an oversight: vendored code is carried unmodified, so a test here would "
         "be testing someone else's project.", "",
         "It is worth stating because the opposite reading is available and wrong. These are "
         "not the risky untested corners of NebulaOS; they are the parts NebulaOS did not "
         "write.", ""]

    consts = {}
    no_test = replaced = 0
    for f in mods:
        path = os.path.join(ext, f)
        name = f[:-3]
        options, _params, commands = _ref.scan(path, consts)
        L.append(f"## `{name}`")
        L.append("")
        if f in prov:
            author, upstream = prov[f]
            L.append(f"**Vendored** - {author}, from {upstream}.")
            L.append("")
        rows = []
        if commands:
            # A replaced upstream command appears twice in the source - once to
            # de-register Klipper's, once to register this one. Listing it twice
            # would read as two commands.
            merged = {}
            for c in commands:
                prev = merged.get(c["name"])
                merged[c["name"]] = bool(c.get("dereg")) or bool(prev)
            cmds = []
            for cname in sorted(merged):
                if merged[cname]:
                    replaced += 1
                    cmds.append(f"`{cname}` *(replaces upstream)*")
                else:
                    cmds.append(f"`{cname}`")
            rows.append(("Registers", ", ".join(cmds)))
        else:
            rows.append(("Registers", "no G-code commands"))
        rows.append(("Reads", f"{len(options)} configuration option(s)"
                     if options else "no configuration"))
        covering = tests_for(name, ext, tests)
        if covering:
            shown = [f"`extras/{t}`" for t in covering[:5]]
            if len(covering) > 5:
                shown.append(f"and {len(covering) - 5} more")
            rows.append(("Tested by", ", ".join(shown)))
        else:
            no_test += 1
            rows.append(("Tested by", "*no test refers to this module*"))
        L.append("| | |")
        L.append("|---|---|")
        for k, v in rows:
            L.append(f"| {k} | {v} |")
        L.append("")
        purpose = _ref.module_purpose(path)
        if purpose:
            for para in purpose.split("\n\n"):
                lines = [x for x in para.split("\n") if x.strip()]
                if not lines:
                    continue
                if any(re.match(r"^(\s{2,}|[-*]\s|\S+\s{2,}\S)", x) for x in lines):
                    L += ["```"] + lines + ["```", ""]
                else:
                    L += textwrap.wrap(" ".join(para.split()), 95) + [""]
        else:
            L.append("*No header comment.*")
            L.append("")

    open(out_path, "w").write("\n".join(L) + "\n")
    print(f"{len(mods)} modules, {no_test} with no test referring to them, "
          f"{replaced} upstream command(s) replaced -> {out_path}")


if __name__ == "__main__":
    main()
